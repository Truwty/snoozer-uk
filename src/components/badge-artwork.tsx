type BadgeArtworkProps = {
  slug: string;
  size?: number;
  className?: string;
};

/** Crisp, consistent vector artwork shared by badge cards and public profiles. */
export function BadgeArtwork({ slug, size = 32, className }: BadgeArtworkProps) {
  // Future catalogue slugs and one-off Owner awards use the matching placeholder
  // until a dedicated symbol is added to the sprite.
  const safeSlug = badgeArtworkSlugs.has(slug) ? slug : "unique";

  return (
    <svg
      className={["badge-artwork", className].filter(Boolean).join(" ")}
      width={size}
      height={size}
      viewBox="0 0 48 48"
      aria-hidden="true"
      focusable="false"
    >
      <use href={"/badges/snoozer-badges.svg#badge-" + safeSlug} />
    </svg>
  );
}
